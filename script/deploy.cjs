const hre  = require("hardhat");
const fs   = require("fs");
const path = require("path");

async function main() {
    console.log("Deploying MedicalVault...");

    const MedicalVault = await hre.ethers.getContractFactory("MedicalVault");
    const contract     = await MedicalVault.deploy();
    await contract.waitForDeployment();

    const address = await contract.getAddress();
    console.log("✅ MedicalVault deployed to:", address);

    // Auto-write address + ABI to src/services/contractConfig.ts
    const configDir  = path.join(__dirname, "../src/services");
    const configFile = path.join(configDir, "contractConfig.ts");
    if (!fs.existsSync(configDir)) fs.mkdirSync(configDir, { recursive: true });

    fs.writeFileSync(configFile, `// Auto-generated by deploy.js — do not edit manually
export const CONTRACT_ADDRESS = "${address}";
export const CONTRACT_ABI = [
  "function addRecord(string memory _cid, string memory _name) public",
  "function setDoctorAccess(address _doctor, bool _status) public",
  "function getRecords(address _patient) public view returns (tuple(string ipfsCid, string fileName, uint256 timestamp, address owner)[])",
  "function authorizedDoctors(address, address) public view returns (bool)",
];
`);

    console.log("✅ Written to src/services/contractConfig.ts");
    console.log("\n📋 MetaMask network settings:");
    console.log("   Network name : Hardhat Local");
    console.log("   RPC URL      : http://127.0.0.1:8545");
    console.log("   Chain ID     : 31337");
    console.log("   Currency     : ETH");
}

main().catch((err) => { console.error(err); process.exit(1); });